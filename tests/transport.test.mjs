import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
let fallbackCalls = 0;
const sdk = { default: async () => {}, EpoxyClientOptions: class {}, EpoxyClient: class { async fetch(url, options) { fallbackCalls++; assert.equal(options.headers.host, undefined); return new Response('ok'); } } };
globalThis.transportTestSdk = sdk;
const source = (await readFile(new URL('../lib/e/requests.mjs', import.meta.url), 'utf8')).replace('import("./http1.mjs")', 'Promise.resolve(globalThis.transportTestSdk)').replace('new URL("./http1.wasm", import.meta.url)', '"test-wasm"');
const { requestHeaders, fetchWithFallback } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
assert.deepEqual(requestHeaders({ Host: 'wrong', Connection: 'x-private', 'x-private': 'remove', 'Content-Length': '99', TE: 'gzip', accept: 'text/html' }), { accept: 'text/html' });
assert.deepEqual(requestHeaders(new Headers({ TE: 'trailers', cookie: 'test=value' })), { cookie: 'test=value', te: 'trailers' });
let fullCalls = 0;
const transport = { opts: {}, wisp: 'test', client: { async fetch() { fullCalls++; throw Error('Http2 PROTOCOL_ERROR'); } } };
const url = new URL('https://example.com/');
assert.equal((await fetchWithFallback(transport, url, 'GET', null, { host: 'wrong' })).status, 200);
assert.equal((await fetchWithFallback(transport, url, 'GET', null, {})).status, 200);
assert.equal(fullCalls, 1);
assert.equal(fallbackCalls, 2);
const unsafe = { ...transport };
await assert.rejects(fetchWithFallback(unsafe, url, 'POST', 'body', {}), /PROTOCOL_ERROR/);
assert.equal(fallbackCalls, 2);
const aborted = new AbortController(); aborted.abort();
await assert.rejects(fetchWithFallback(transport, url, 'GET', null, {}, aborted.signal), { name: 'AbortError' });
assert.equal(fallbackCalls, 2);
const failing = { ...transport, client: { async fetch() { throw Error('certificate validation failed'); } } };
await assert.rejects(fetchWithFallback(failing, url, 'GET', null, {}), /certificate validation/);
assert.equal(fallbackCalls, 2);
let finish;
const waiting = { ...transport, client: { fetch: () => new Promise(resolve => { finish = resolve; }) } };
const controller = new AbortController();
const request = fetchWithFallback(waiting, url, 'GET', null, {}, controller.signal);
controller.abort();
await assert.rejects(request, { name: 'AbortError' });
finish(new Response('late'));
delete globalThis.transportTestSdk;
console.log('transport header, fallback, no-POST-replay, TLS and abort checks passed');
